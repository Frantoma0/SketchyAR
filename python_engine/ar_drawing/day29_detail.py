"""Day 29 — five nested real detail levels of the active V4 Sketch engine.

Scores are generated by the unchanged V4 importance/ETF/FDoG pipeline and
cached per SHA-256 grayscale input, size and sigma inside its module.  The
levels differ ONLY in the final hysteresis threshold; no expensive flow
recomputation is required when selecting a new detail for the same source.

D1 subset D2 subset D3 subset D4 subset D5 (exact pixel inclusion).
D3 uses the same threshold as V4 Day 28, for a compatible visual baseline.
The output is still an opaque-black / transparent 0-or-1 mask, not grayscale.
"""
from __future__ import annotations
import numpy as np
from .day12_edges import hysteresis_threshold
from .day13_bridge import BridgeResult
from .day28_flow_coherent import get_cached_flow_score

SKETCH_QUALITY_VERSION = 'day29-v4-detail-v1'
BRIDGE_VERSION = 'day29-gray8-detail-v1'
DETAIL_FACTORS = (1.55, 1.25, 1.0, 0.80, 0.63)


def select_detail_contours(score: np.ndarray, detail: int,
                           *, low: float = 0.04, high: float = 0.10) -> np.ndarray:
    """Nested threshold masks for D1...D5, with a common V4 score map.

    Using one positive-score quantile and strictly ordered multipliers makes
    every lower-detail result a subset of every higher-detail result.  A
    stable 8-connected hysteresis keeps weak portions only if joined to a
    strong segment.  Isolated weak noise is not introduced by a separate,
    level-dependent morphology that might violate the nesting invariant.
    """
    if type(detail) is not int or not 1 <= detail <= 5:
        raise ValueError('Detail must be integer in 1..5')
    raw = np.asarray(score)
    if raw.ndim != 2 or not raw.size or raw.dtype.kind != 'f' or not np.isfinite(raw).all() or np.any(raw < 0):
        raise ValueError('Score must be finite nonnegative float HxW')
    if not np.isfinite(low) or not np.isfinite(high) or low < 0 or high <= 0 or high > 1 or low > high:
        raise ValueError('Invalid V4 threshold settings')
    valid = raw[raw > np.float32(1e-5)]
    if valid.size < 4:
        return np.zeros(raw.shape, dtype=np.bool_)
    base = float(np.clip(np.percentile(valid, 81), max(0.006, .36 * low), max(.006, 1.10 * high)))
    threshold = base * DETAIL_FACTORS[detail - 1]
    return hysteresis_threshold(raw.astype(np.float32, copy=False), 0.46 * threshold, threshold)


def process_gray8_detail(data: bytes | bytearray | memoryview, width: int, height: int,
                         sigma: float = 1.0, low: float = 0.04, high: float = 0.10,
                         detail: int = 3) -> BridgeResult:
    if type(detail) is not int or not 1 <= detail <= 5:
        raise ValueError('Detail must be integer in 1..5')
    # V4 helper validates source length, width/height and parameters BEFORE
    # any cache lookup and hashes bytes (no untrusted photo kept in the cache).
    score = get_cached_flow_score(data, width, height, sigma=sigma, low=low, high=high)
    mask = select_detail_contours(score, detail, low=low, high=high)
    return BridgeResult(mask.astype(np.uint8).tobytes(), width, height,
                        int(np.count_nonzero(mask)),
                        engine_version=SKETCH_QUALITY_VERSION,
                        bridge_version=BRIDGE_VERSION)
